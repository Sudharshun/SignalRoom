function spark(base: number, variance: number, n = 24): { t: number; v: number }[] {
  const out = []
  for (let i = 0; i < n; i++) {
    const wobble = Math.sin(i / 2.4) * variance + (i % 3 === 0 ? variance * 0.3 : 0)
    out.push({ t: i, v: Math.max(0, +(base + wobble).toFixed(2)) })
  }
  return out
}

